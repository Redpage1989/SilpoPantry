/**
 * `\b` тут безпечний: усі ключі словника — ASCII-латиниця, а пастка
 * «\b не працює з кирилицею» (див. includesWord у matching.ts) стосується
 * кириличних шаблонів. Межа латинського слова видна і впритул до кирилиці.
 */
const LATIN_FOOD_RE = new RegExp(`\\b(?:${Object.keys(LATIN_FOOD_TERMS).join('|')})\\b`, 'gi')

/** Замінює латинські харчові терміни кириличними; решту тексту не чіпає. */
export function transliterateLatinFoodTerms(text: string): string {
  return text.replace(LATIN_FOOD_RE, (word) => LATIN_FOOD_TERMS[word.toLowerCase()])
}

